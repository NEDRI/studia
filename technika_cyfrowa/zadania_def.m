function Z = zadania_def()
%ZADANIA_DEF  Opis układów z zadań 3 i 4 (wspólny dla budowy i weryfikacji).
%
%   Każdy podpunkt ma dwa układy na tych samych wejściach:
%     zad. 3: układ pierwotny  (F)  i uproszczony      (F_upr)
%     zad. 4: układ zbudowany  (Y)  i bramka wzorcowa  (Y_wz)
%   Bramka to wiersz {id, operator, {wejścia}, etykieta}. Wejściem może być
%   zmienna (A, B, C, D) albo id wcześniejszej bramki. Etykieta staje się
%   nazwą bloku w Simulinku, więc w jednym podsystemie musi być unikalna.
%   f1/f2 to te same funkcje zapisane w MATLAB-ie (do kontroli symulacji).

Z = struct('id',{},'vars',{},'outNames',{},'gates1',{},'out1',{},'gates2',{}, ...
           'out2',{},'title1',{},'title2',{},'opis',{},'f1',{},'f2',{});

%% ---------------- Zadanie 3: upraszczanie wyrażeń ----------------
P = {'F','F_upr','XOR'};

Z(end+1) = def('3a', 'AB', P, ...
    {'nA','NOT',{'A'},'¬A'
     'nB','NOT',{'B'},'¬B'
     'g1','AND',{'nA','B'},'¬A·B'
     'g2','AND',{'A','nB'},'A·¬B'
     'g3','AND',{'A','B'},'A·B'
     'F', 'OR', {'g1','g2','g3'},'¬A·B + A·¬B + A·B'}, 'F', ...
    {'F','OR',{'A','B'},'A + B'}, 'F', ...
    'Układ pierwotny: F = ¬A·B + A·¬B + A·B', 'Układ uproszczony: F = A + B', ...
    '3a)  F = ¬A·B + A·¬B + A·B   =   A + B', ...
    @(A,B,C,D) (~A&B) | (A&~B) | (A&B), @(A,B,C,D) A|B);

Z(end+1) = def('3b', 'ABC', P, ...
    {'nA','NOT',{'A'},'¬A'
     'nB','NOT',{'B'},'¬B'
     'g1','AND',{'nA','nB','C'},'¬A·¬B·C'
     'g2','AND',{'nA','B','C'},'¬A·B·C'
     'g3','AND',{'A','nB','C'},'A·¬B·C'
     'g4','AND',{'A','B','C'},'A·B·C'
     'F', 'OR', {'g1','g2','g3','g4'},'¬A¬BC + ¬ABC + A¬BC + ABC'}, 'F', ...
    cell(0,4), 'C', ...
    'Układ pierwotny: F = ¬A·¬B·C + ¬A·B·C + A·¬B·C + A·B·C', ...
    'Układ uproszczony: F = C (bez bramek, przewód z wejścia C)', ...
    '3b)  F = ¬A·¬B·C + ¬A·B·C + A·¬B·C + A·B·C   =   C', ...
    @(A,B,C,D) (~A&~B&C) | (~A&B&C) | (A&~B&C) | (A&B&C), @(A,B,C,D) C);

Z(end+1) = def('3c', 'AB', P, ...
    {'nA','NOT',{'A'},'¬A'
     'nB','NOT',{'B'},'¬B'
     's1','OR', {'A','nB'},'A + ¬B'
     's2','OR', {'nA','B'},'¬A + B'
     's3','OR', {'A','B'},'A + B'
     'F', 'AND',{'s1','s2','s3'},'(A+¬B)·(¬A+B)·(A+B)'}, 'F', ...
    {'F','AND',{'A','B'},'A·B'}, 'F', ...
    'Układ pierwotny: F = (A + ¬B)·(¬A + B)·(A + B)', 'Układ uproszczony: F = A·B', ...
    '3c)  F = (A + ¬B)·(¬A + B)·(A + B)   =   A·B', ...
    @(A,B,C,D) (A|~B) & (~A|B) & (A|B), @(A,B,C,D) A&B);

Z(end+1) = def('3d', 'ABC', P, ...
    {'nB','NOT', {'B'},'¬B'
     'p1','AND', {'A','B','C'},'A·B·C'
     'p2','NAND',{'A','nB','C'},'¬(A·¬B·C)'
     's', 'OR',  {'A','B','C'},'A + B + C'
     'F', 'AND', {'p1','p2','s'},'ABC·¬(A¬BC)·(A+B+C)'}, 'F', ...
    {'F','AND',{'A','B','C'},'A·B·C (upr.)'}, 'F', ...
    'Układ pierwotny: F = A·B·C·¬(A·¬B·C)·(A + B + C)', 'Układ uproszczony: F = A·B·C', ...
    '3d)  F = A·B·C·¬(A·¬B·C)·(A + B + C)   =   A·B·C', ...
    @(A,B,C,D) (A&B&C) & ~(A&~B&C) & (A|B|C), @(A,B,C,D) A&B&C);

Z(end+1) = def('3e', 'ABCD', P, ...
    {'nA','NOT',{'A'},'¬A'
     'nC','NOT',{'C'},'¬C'
     'g1','AND',{'nA','B','nC','D'},'¬A·B·¬C·D'
     'g2','AND',{'nA','B','C','D'},'¬A·B·C·D'
     'g3','AND',{'A','B','nC','D'},'A·B·¬C·D'
     'g4','AND',{'A','B','C','D'},'A·B·C·D'
     'F', 'OR', {'g1','g2','g3','g4'},'¬AB¬CD + ¬ABCD + AB¬CD + ABCD'}, 'F', ...
    {'F','AND',{'B','D'},'B·D'}, 'F', ...
    'Układ pierwotny: F = ¬A·B·¬C·D + ¬A·B·C·D + A·B·¬C·D + A·B·C·D', ...
    'Układ uproszczony: F = B·D', ...
    '3e)  F = ¬A·B·¬C·D + ¬A·B·C·D + A·B·¬C·D + A·B·C·D   =   B·D', ...
    @(A,B,C,D) (~A&B&~C&D) | (~A&B&C&D) | (A&B&~C&D) | (A&B&C&D), @(A,B,C,D) B&D);

Z(end+1) = def('3f', 'AB', P, ...
    {'nB','NOT', {'B'},'¬B'
     's1','OR',  {'A','B'},'A + B'
     's2','OR',  {'nB','A'},'¬B + A'
     'F', 'NAND',{'s1','s2'},'¬((A+B)·(¬B+A))'}, 'F', ...
    {'F','NOT',{'A'},'¬A'}, 'F', ...
    'Układ pierwotny: F = ¬((A + B)·(¬B + A))', 'Układ uproszczony: F = ¬A', ...
    '3f)  F = ¬((A + B)·(¬B + A))   =   ¬A', ...
    @(A,B,C,D) ~((A|B) & (~B|A)), @(A,B,C,D) ~A);

Z(end+1) = def('3g', 'AB', P, ...
    {'x', 'XOR',{'A','B'},'A ⊕ B'
     'p', 'AND',{'A','B'},'A·B'
     'F', 'OR', {'x','p'},'(A⊕B) + A·B'}, 'F', ...
    {'F','OR',{'A','B'},'A + B'}, 'F', ...
    'Układ pierwotny: F = (A ⊕ B) + A·B', 'Układ uproszczony: F = A + B', ...
    '3g)  F = (A ⊕ B) + A·B   =   A + B', ...
    @(A,B,C,D) xor(A,B) | (A&B), @(A,B,C,D) A|B);

%% ---------------- Zadanie 4: bramki z podanych elementów ----------------
P = {'Y','Y_wz','XOR'};

Z(end+1) = def('4a', 'AB', P, ...
    {'nA','NOT',{'A'},'¬A'
     'nB','NOT',{'B'},'¬B'
     'p', 'AND',{'nA','nB'},'¬A·¬B'
     'Y', 'NOT',{'p'},'¬(¬A·¬B)'}, 'Y', ...
    {'Y','OR',{'A','B'},'OR (wzorzec)'}, 'Y', ...
    'Układ tylko z AND i NOT: Y = ¬(¬A·¬B) = A + B', 'Bramka wzorcowa: OR', ...
    '4a)  OR z AND i NOT:   A + B = ¬(¬A·¬B)', ...
    @(A,B,C,D) ~(~A & ~B), @(A,B,C,D) A|B);

Z(end+1) = def('4b', 'AB', P, ...
    {'nA','NOT',{'A'},'¬A'
     'nB','NOT',{'B'},'¬B'
     's', 'OR', {'nA','nB'},'¬A + ¬B'
     'Y', 'NOT',{'s'},'¬(¬A + ¬B)'}, 'Y', ...
    {'Y','AND',{'A','B'},'AND (wzorzec)'}, 'Y', ...
    'Układ tylko z OR i NOT: Y = ¬(¬A + ¬B) = A·B', 'Bramka wzorcowa: AND', ...
    '4b)  AND z OR i NOT:   A·B = ¬(¬A + ¬B)', ...
    @(A,B,C,D) ~(~A | ~B), @(A,B,C,D) A&B);

Z(end+1) = def('4c', 'AB', P, ...
    {'p','AND',{'A','B'},'A·B'
     'Y','NOT',{'p'},'¬(A·B)'}, 'Y', ...
    {'Y','NAND',{'A','B'},'NAND (wzorzec)'}, 'Y', ...
    'Układ tylko z AND i NOT: Y = ¬(A·B)', 'Bramka wzorcowa: NAND', ...
    '4c)  NAND z AND i NOT:   ¬(A·B)', ...
    @(A,B,C,D) ~(A&B), @(A,B,C,D) ~(A&B));

Z(end+1) = def('4d', 'AB', P, ...
    {'nA','NOT',{'A'},'¬A'
     'nB','NOT',{'B'},'¬B'
     'p1','AND',{'nA','B'},'¬A·B'
     'p2','AND',{'A','nB'},'A·¬B'
     'Y', 'OR', {'p1','p2'},'¬A·B + A·¬B'}, 'Y', ...
    {'Y','XOR',{'A','B'},'XOR (wzorzec)'}, 'Y', ...
    'Układ z OR, AND i NOT: Y = ¬A·B + A·¬B', 'Bramka wzorcowa: XOR', ...
    '4d)  XOR z OR, AND i NOT:   A ⊕ B = ¬A·B + A·¬B', ...
    @(A,B,C,D) (~A&B) | (A&~B), @(A,B,C,D) xor(A,B));

Z(end+1) = def('4e', 'AB', P, ...
    {'s','OR', {'A','B'},'A + B'
     'x','XOR',{'A','B'},'A ⊕ B'
     'Y','XOR',{'s','x'},'(A+B) ⊕ (A⊕B)'}, 'Y', ...
    {'Y','AND',{'A','B'},'AND (wzorzec)'}, 'Y', ...
    'Układ tylko z XOR i OR: Y = (A + B) ⊕ (A ⊕ B) = A·B', 'Bramka wzorcowa: AND', ...
    '4e)  AND z XOR i OR:   A·B = (A + B) ⊕ (A ⊕ B)', ...
    @(A,B,C,D) xor(A|B, xor(A,B)), @(A,B,C,D) A&B);

Z(end+1) = def('4f', 'AB', P, ...
    {'n1','NAND',{'A','B'},'N1 = ¬(A·B)'
     'n2','NAND',{'A','n1'},'N2 = ¬(A·N1)'
     'n3','NAND',{'B','n1'},'N3 = ¬(B·N1)'
     'Y', 'NAND',{'n2','n3'},'Y = ¬(N2·N3)'}, 'Y', ...
    {'Y','XOR',{'A','B'},'XOR (wzorzec)'}, 'Y', ...
    'Układ tylko z NAND: Y = ¬(N2·N3) = A ⊕ B', 'Bramka wzorcowa: XOR', ...
    '4f)  XOR z samych NAND (4 bramki)', ...
    @(A,B,C,D) ~(~(A & ~(A&B)) & ~(B & ~(A&B))), @(A,B,C,D) xor(A,B));
end

function s = def(id, vars, outNames, g1, o1, g2, o2, t1, t2, opis, f1, f2)
s.id = id;
s.vars = num2cell(vars);          % 'AB' -> {'A','B'}
s.outNames = outNames;
s.gates1 = g1;   s.out1 = o1;     % out = id bramki wyjściowej albo nazwa wejścia
s.gates2 = g2;   s.out2 = o2;
s.title1 = t1;   s.title2 = t2;
s.opis = opis;
s.f1 = f1;       s.f2 = f2;
end
